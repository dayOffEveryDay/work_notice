import { readFile } from 'node:fs/promises';

export function parseLocalSecrets(file) {
  const keys = new Map();
  const lines = file.split(/\r?\n/);
  for (const name of ['AGENT_HMAC_SECRET', 'ADMIN_API_KEY']) {
    const matches = lines.filter(line => line.startsWith(name + '='));
    const value = matches[0]?.slice(name.length + 1);
    if (matches.length !== 1 || !/^[0-9a-f]{64}$/.test(value ?? ''))
      throw new Error('Expected .dev.vars generated by New-LocalSecrets.ps1; use interactive wrangler secret put for other formats.');
    keys.set(name, value);
  }
  if (keys.get('AGENT_HMAC_SECRET') === keys.get('ADMIN_API_KEY')) throw new Error('Keys must be independent');
  return keys;
}
export async function loadLocalSecrets() { return parseLocalSecrets(await readFile(new URL('../.dev.vars', import.meta.url), 'utf8')); }
